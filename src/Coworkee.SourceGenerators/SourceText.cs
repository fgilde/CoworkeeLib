using Microsoft.CodeAnalysis;

namespace Coworkee.SourceGenerators;

internal static class SourceText
{
    public const string Header = "// <auto-generated/>\n#nullable enable\n#pragma warning disable\n";

    private static readonly SymbolDisplayFormat Format =
        SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    public static string Type(ITypeSymbol type) => type.ToDisplayString(Format);

    public static string Literal(string value) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, quote: true);

    public static string Identifier(string name) => "@" + name;
}
