using Coworkee.Cli.Commands;
using Coworkee.Cli.Generation;
using Coworkee.Cli.Spec;

namespace Coworkee.Cli.Tests;

public sealed class CodeGenTests(TemplateFixture template)
{
    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private static EntitySpec Customer => Named("Customer");

    private static EntitySpec Named(string name, MappingStrategy? mapping = null) =>
        new() { Name = name, Mapping = mapping, Properties = [new PropertySpec { Name = "Name", Required = true, MaxLength = 200 }] };

    private static EntitySpec Order => OrderWith(null);

    private static EntitySpec OrderWith(MappingStrategy? mapping) => new()
    {
        Name = "Order",
        Mapping = mapping,
        Properties =
        [
            new PropertySpec { Name = "Number", Required = true, MaxLength = 50 },
            new PropertySpec { Name = "Total", Type = PropertyType.Money },
            new PropertySpec { Name = "Customer", Type = PropertyType.Reference, Reference = "Customer", Required = true, Inverse = "Orders" },
        ],
    };

    private static string Content(IEnumerable<GeneratedFile> files, string suffix) => files.Single(f => f.Path.EndsWith(suffix, StringComparison.Ordinal)).Content;

    private static string Read(string app, string path) => File.ReadAllText(Path.Combine(app, path));

    [Theory]
    [InlineData("module add Orders --codegen", true, MappingStrategy.Mapperly)]
    [InlineData("module add Orders --codegen --mapping Manual", true, MappingStrategy.Manual)]
    [InlineData("module add Orders --codegen --mapping Mapperly", true, MappingStrategy.Mapperly)]
    [InlineData("module add Orders", false, MappingStrategy.Manual)]
    [InlineData("entity add Orders Coupon --codegen", true, MappingStrategy.Mapperly)]
    public void Codegen_maps_with_Mapperly_unless_the_mapping_says_Manual(string line, bool codeGen, MappingStrategy mapping)
    {
        var result = CliApp.Build().Parse(line);

        result.Errors.ShouldBeEmpty();
        result.GetValue(FeatureOptions.CodeGen).ShouldBe(codeGen);
        FeatureOptions.Entity(result, "Order").Mapping.ShouldBe(mapping);
    }

    [Fact]
    public void A_generated_entity_carries_the_attribute_instead_of_a_written_dto_and_mapping()
    {
        var index = new SpecIndex(new AppSpec { Name = "Shop", Modules = [new ModuleSpec { Name = "Sales", Entities = [Customer, Order] }] });
        var order = FeatureWriter.Files(new EntityModel("Shop", "Sales", Order, MappingStrategy.Mapperly, index, CodeGen: true)).ToList();
        var customer = FeatureWriter.Files(new EntityModel("Shop", "Sales", Customer, MappingStrategy.Manual, index, CodeGen: true)).ToList();

        order.ShouldNotContain(f => f.Path.EndsWith("OrderDto.cs", StringComparison.Ordinal) || f.Path.EndsWith("OrderMapping.cs", StringComparison.Ordinal));
        var domain = Content(order, "Domain/Order.cs");
        domain.ShouldContain("using Nextended.Core.Attributes;\nusing Nextended.Core.Enums;\n");
        domain.ShouldContain("[AutoGenerateDto(Namespace = \"Shop.Contracts.Sales\", MappingStrategy = DtoMappingStrategy.Mapperly)]\npublic sealed class Order");
        var customerDomain = Content(customer, "Domain/Customer.cs");
        customerDomain.ShouldContain("[AutoGenerateDto(Namespace = \"Shop.Contracts.Sales\")]\npublic sealed class Customer");
        customerDomain.ShouldNotContain("Nextended.Core.Enums");
        customerDomain.ShouldContain("    [IgnoreOnGeneration]\n    public List<Order> Orders { get; set; } = [];");

        // the rest compiles against the generated OrderDto and its ToDto() unchanged
        Content(order, "AddEditOrder.cs").ShouldContain("return entity.ToDto();");
        Content(order, "OrdersPage.razor").ShouldContain("T=\"OrderDto\"");

        var written = FeatureWriter.Files(new EntityModel("Shop", "Sales", Order, MappingStrategy.Mapperly, index)).ToList();
        Content(written, "Domain/Order.cs").ShouldNotContain("AutoGenerateDto");
        Content(written, "Domain/Order.cs").ShouldNotContain("IgnoreOnGeneration");
    }

    [Fact]
    public void A_generated_module_references_the_package_and_gets_a_codegen_json()
    {
        var files = ServerFiles.Module("Shop", "Sales", [new EntityModel("Shop", "Sales", Customer, MappingStrategy.Manual, CodeGen: true)]).ToList();

        Content(files, "Shop.Sales.csproj").ShouldContain("<CoworkeePackage Include=\"Coworkee.CodeGen\" />");
        Content(files, "Shop.Sales.csproj").ShouldNotContain("Riok.Mapperly");
        var config = Content(files, "src/Shop.Sales/codegen.json");
        config.ShouldContain("\"Namespace\": \"Shop.Sales\"");
        config.ShouldContain("\"OutputPath\": \"../Shop.Contracts/Sales/Generated/\"");
        config.ShouldContain("\"MappingOutputPath\": \"./Generated/\"");
        config.ShouldContain("\"PropertiesToIgnore\": [ \"TenantId\", \"CreatedAt\", \"CreatedBy\", \"ModifiedAt\", \"ModifiedBy\", \"IsDeleted\", \"DeletedAt\", \"DeletedBy\" ]");
        config.ShouldContain("\"CreateFileHeaders\": false");
        System.Text.Json.JsonDocument.Parse(config).RootElement.GetProperty("DtoGeneration").GetProperty("DeepProperties").GetBoolean().ShouldBeTrue();

        ServerFiles.Module("Shop", "Sales", [new EntityModel("Shop", "Sales", Customer, MappingStrategy.Manual)]).ShouldNotContain(f => f.Path.EndsWith("codegen.json", StringComparison.Ordinal));
        Content(ServerFiles.Module("Shop", "Sales", [new EntityModel("Shop", "Sales", Customer, MappingStrategy.Manual)]), "Shop.Sales.csproj").ShouldNotContain("Coworkee.CodeGen");
    }

    [Fact]
    public async Task Entity_add_with_codegen_adds_package_and_codegen_json_once_and_keeps_an_existing_one()
    {
        using var app = GenerationTests.MinimalApp();
        var solution = Solution.Find(app.Path);
        (await ModuleCommand.AddAsync(solution, new ModuleSpec { Name = "Sales", Entities = [Customer] }, Ct)).ShouldBe(0);
        var config = Path.Combine(app.Path, "src/Shop.Sales/codegen.json");
        File.Exists(config).ShouldBeFalse();

        (await EntityCommand.AddAsync(solution, "Sales", new EntitySpec { Name = "Coupon", Mapping = MappingStrategy.Mapperly, Properties = [new PropertySpec { Name = "Code", Required = true }] }, Ct, codeGen: true)).ShouldBe(0);

        File.ReadAllText(config).ShouldContain("../Shop.Contracts/Sales/Generated/");
        File.Exists(Path.Combine(app.Path, "src/Shop.Contracts/Sales/CouponDto.cs")).ShouldBeFalse();
        File.Exists(Path.Combine(app.Path, "src/Shop.Sales/Features/Coupons/CouponMapping.cs")).ShouldBeFalse();
        File.Exists(Path.Combine(app.Path, "src/Shop.Contracts/Sales/CustomerDto.cs")).ShouldBeTrue();
        var project = Read(app.Path, "src/Shop.Sales/Shop.Sales.csproj");
        project.ShouldContain("<CoworkeePackage Include=\"Coworkee.CodeGen\" />");
        project.ShouldContain("Riok.Mapperly");
        var packages = Read(app.Path, "Directory.Packages.props");
        packages.ShouldContain("<PackageVersion Include=\"Coworkee.CodeGen\" Version=\"$(CoworkeeVersion)\" />");
        packages.ShouldContain("Riok.Mapperly");

        File.WriteAllText(config, "{ \"DtoGeneration\": { \"Namespace\": \"Mine\" } }");
        (await EntityCommand.AddAsync(solution, "Sales", new EntitySpec { Name = "Voucher", Mapping = MappingStrategy.Manual, Properties = [new PropertySpec { Name = "Code" }] }, Ct, codeGen: true)).ShouldBe(0);

        File.ReadAllText(config).ShouldBe("{ \"DtoGeneration\": { \"Namespace\": \"Mine\" } }");
        Read(app.Path, "src/Shop.Sales/Shop.Sales.csproj").Split("Coworkee.CodeGen").Length.ShouldBe(2);
        Read(app.Path, "Directory.Packages.props").Split("Coworkee.CodeGen").Length.ShouldBe(2);
    }

    [Fact]
    public async Task A_generated_dto_can_only_reference_generated_entities_of_its_module()
    {
        using var app = GenerationTests.MinimalApp();
        var solution = Solution.Find(app.Path);
        (await ModuleCommand.AddAsync(solution, new ModuleSpec { Name = "Crm", Entities = [Customer] }, Ct)).ShouldBe(0);
        var order = new EntitySpec { Name = "Order", Properties = [new PropertySpec { Name = "Customer", Type = PropertyType.Reference, Reference = "Customer" }] };

        (await Should.ThrowAsync<CliException>(() => EntityCommand.AddAsync(solution, "Crm", order, Ct, codeGen: true))).Message.ShouldContain("Crm.Customer, whose DTO is not generated");
        File.Exists(Path.Combine(app.Path, "src/Shop.Crm/Domain/Order.cs")).ShouldBeFalse();

        (await ModuleCommand.AddAsync(solution, new ModuleSpec { Name = "Sales", Entities = [Named("Buyer")] }, Ct, codeGen: true)).ShouldBe(0);
        var invoice = new EntitySpec { Name = "Invoice", Properties = [new PropertySpec { Name = "Buyer", Type = PropertyType.Reference, Reference = "Buyer" }] };
        (await EntityCommand.AddAsync(solution, "Sales", invoice, Ct, codeGen: true)).ShouldBe(0);
        var invoiceOfCrm = new EntitySpec { Name = "Bill", Properties = [new PropertySpec { Name = "Customer", Type = PropertyType.Reference, Reference = "Crm.Customer" }] };
        await Should.ThrowAsync<CliException>(() => EntityCommand.AddAsync(solution, "Sales", invoiceOfCrm, Ct, codeGen: true));
    }

    [Fact]
    public async Task A_module_added_with_codegen_builds_after_the_cli_generated_its_dtos()
    {
        var feed = Environment.GetEnvironmentVariable("COWORKEE_TEST_FEED");
        Assert.SkipWhen(string.IsNullOrEmpty(feed), "Set COWORKEE_TEST_FEED to a folder with packed Coworkee packages (build/pack-local.ps1) to build a generated app.");
        var app = await template.CreateAsync("codegen", "--samples", "false");
        await Dotnet.RunAsync(app, "nuget", "add", "source", Path.GetFullPath(feed!), "--name", "local", "--configfile", "nuget.config");
        var solution = Solution.Find(app);
        var module = new ModuleSpec { Name = "Sales", Entities = [Named("Customer", MappingStrategy.Manual), OrderWith(MappingStrategy.Mapperly)] };

        (await ModuleCommand.AddAsync(solution, module, Ct, codeGen: true)).ShouldBe(0);
        await CodeGenFiles.PrimeAsync(solution, "Sales", ["Customer", "Order"], Ct);

        var orderDto = Read(app, "src/Shop.Contracts/Sales/Generated/OrderDto.g.cs");
        orderDto.ShouldContain("public Shop.Contracts.Sales.CustomerDto? Customer { get; set; }");
        orderDto.ShouldContain("public string Number { get; set; }");
        orderDto.ShouldNotContain("TenantId");
        Read(app, "src/Shop.Contracts/Sales/Generated/CustomerDto.g.cs").ShouldNotContain("Orders");
        Read(app, "src/Shop.Sales/Generated/OrderMapper.g.cs").ShouldContain("[UseStaticMapper(typeof(Shop.Sales.MappingExtensions))]");
        File.Exists(Path.Combine(app, "src/Shop.Sales/Generated/MappingExtensions.g.Customer.cs")).ShouldBeTrue();
        await Dotnet.RunAsync(app, "build", "Shop.slnx");
    }
}
